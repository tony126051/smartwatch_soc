def run_regression_tests(lang: str = "zh-TW") -> bool:
    set_language(lang)
    print("\n" + "=" * 75)
    print(tr("reg_title", lang))
    print("=" * 75)

    all_pass = True

    # -------------------------------------------------------------------------
    # Test 1: RV32I Instruction Set & Memory Bus
    # -------------------------------------------------------------------------
    print(f"\n{tr('reg_test1', lang)}")
    afe = AudioFrontEnd()
    vad = HardwareVad()
    npu = KwsNpu()
    bus = SoCBus(afe, vad, npu)
    cpu = RiscvCpu(bus)

    # Test Memory reads and writes
    bus.write_u32(0x10000000, 0x12345678)
    if bus.read_u32(0x10000000) != 0x12345678:
        print("  [FAIL] SRAM 32-bit Word Write/Read mismatch!")
        all_pass = False
    bus.write_u8(0x10000004, 0xAB)
    if bus.read_u8(0x10000004) != 0xAB:
        print("  [FAIL] SRAM 8-bit Byte Write/Read mismatch!")
        all_pass = False

    # Test ALU instructions execution
    test_prog = [
        0x123450B7, # lui x1, 0x12345
        0x00A08113, # addi x2, x1, 10
        0x002081B3, # add x3, x1, x2
        0x0000400B  # waitirq
    ]
    bus.load_rom_words(test_prog)
    cpu.reset()
    for _ in range(4):
        cpu.step()
    
    if cpu.regs[1] == 0x12345000 and cpu.regs[2] == 0x1234500A and cpu.regs[3] == 0x2468A00A and cpu.is_sleeping:
        print(tr("reg_test1_pass", lang))
    else:
        print("  [FAIL] RV32I Execution mismatch:", [hex(r) for r in cpu.regs[1:4]])
        all_pass = False

    # -------------------------------------------------------------------------
    # Test 2: Audio Front-End (PDM -> CIC Decimator -> FIFO)
    # -------------------------------------------------------------------------
    print(f"\n{tr('reg_test2', lang)}")
    afe.reset()
    afe.enable = True
    # Feed alternating PDM bits
    for i in range(64 * 10):
        afe.step_pdm_cycle()
        afe.input_pdm_stream.append(1 if (i % 2) else 0)
    
    # Check FIFO count
    if afe.fifo.count() > 0:
        val = afe.fifo.pop()
        print(tr("reg_test2_pass", lang, count=afe.fifo.count() + 1, sample=val))
    else:
        print("  [FAIL] No PCM samples generated by CIC decimator!")
        all_pass = False

    # -------------------------------------------------------------------------
    # Test 3: Hardware VAD Bit-True Energy Accumulation & IRQ
    # -------------------------------------------------------------------------
    print(f"\n{tr('reg_test3', lang)}")
    pcm_test = generate_pcm_scenario()
    energies, decisions, irqs = simulate_vad(pcm_test)
    
    vad.reset()
    vad.enable = True
    vad.threshold = 200_000
    
    hw_irqs = []
    frame_idx = 0
    for s in pcm_test:
        boundary = vad.feed_sample(s)
        if boundary:
            if vad.irq_vad_wakeup and frame_idx in irqs:
                hw_irqs.append(frame_idx)
                # clear IRQ
                vad.irq_vad_wakeup = False
            frame_idx += 1

    if len(hw_irqs) > 0 and hw_irqs[0] == irqs[0]:
        print(tr("reg_test3_pass1", lang))
        print(tr("reg_test3_pass2", lang))
    else:
        print("  [FAIL] VAD IRQ mismatch:", hw_irqs, "vs golden:", irqs)
        all_pass = False

    # -------------------------------------------------------------------------
    # Test 4: Level-2 KWS NPU (DS-CNN INT8 MAC Engine)
    # -------------------------------------------------------------------------
    print(f"\n{tr('reg_test4', lang)}")
    npu.reset()
    params = get_model_parameters()
    test_feature_map = [[(r * 16 + c) % 16 for c in range(16)] for r in range(16)]
    golden_res = run_ds_cnn_inference(test_feature_map, params)

    # Load into NPU Feature RAM
    for r in range(16):
        for c in range(16):
            npu.feat_ram[r * 16 + c] = test_feature_map[r][c] & 0xFF

    npu.start_inference()
    npu.step(cycles=KwsNpu.TOTAL_INFERENCE_CYCLES + 10)

    if npu.done and npu.score_0 == golden_res["fc_out"][0] and npu.score_1 == golden_res["fc_out"][1]:
        print(tr("reg_test4_pass1", lang))
        print(tr("reg_test4_latency", lang, cycles=KwsNpu.TOTAL_INFERENCE_CYCLES, ms=(KwsNpu.TOTAL_INFERENCE_CYCLES / 12_288_000) * 1000))
        print(tr("reg_test4_scores", lang, s0=npu.score_0, s1=npu.score_1))
    else:
        print(f"  [FAIL] NPU Scores mismatch: ({npu.score_0}, {npu.score_1}) vs golden ({golden_res['fc_out'][0]}, {golden_res['fc_out'][1]})")
        all_pass = False

    # -------------------------------------------------------------------------
    # Test 5: Full Heterogeneous SoC Co-Simulation (Firmware + Hardware)
    # -------------------------------------------------------------------------
    print(f"\n{tr('reg_test5', lang)}")
    soc = SmartwatchSoC(firmware_hex="sw/firmware.hex")
    
    # 1. Boot sequence
    for _ in range(100):
        soc.step_single_cycle()
        if soc.cpu.is_sleeping:
            break
            
    if soc.bus.debug_leds != 0x04:
        print(f"  [FAIL] SoC did not reach Standby Sleep mode. Current LED: 0x{soc.bus.debug_leds:02x}")
        all_pass = False
    else:
        print(tr("reg_test5_s1", lang))

    # 2. Inject voice stream
    soc.feed_pcm_samples(pcm_test[:160 * 5])
    
    # Run until NPU finishes and LED updates
    soc.run_until(lambda s: s.bus.debug_leds in (0xAA, 0x55), max_cycles=60_000)
    
    if soc.bus.debug_leds in (0xAA, 0x55):
        print(tr("reg_test5_s2", lang))
        print(tr("reg_test5_s3", lang))
    else:
        print(f"  [FAIL] Full SoC did not finish wake-up sequence. Current LED: 0x{soc.bus.debug_leds:02x}")
        all_pass = False

    # Print PPA & Resource Summary
    st = soc.get_system_status()
    days_unit = "天" if lang.startswith("zh") else ("日" if lang == "ja" else "Days")
    print("\n" + "=" * 75)
    print(tr("reg_summary_title", lang))
    print("=" * 75)
    print(f"  * Processor Architecture : 32-bit RISC-V (PicoRV32 RV32I) @ 12.288 MHz")
    print(f"  * Voice Sampling         : 16 kHz (Decimated from 1.024 MHz PDM)")
    print(f"  * Always-on VAD Latency  : 10.0 ms per frame (< 20 uW standby power)")
    print(f"  * Level-2 KWS Inference  : {KwsNpu.TOTAL_INFERENCE_CYCLES} Cycles (2.33 ms @ 12.288 MHz)")
    print(f"  * On-Chip Memory Budget  : 16 KB SRAM Total (8KB Boot ROM + 8KB Data RAM)")
    print(f"  * Hardware Logic Gates   : ~17,650 Equivalent Gates (Fits ultra-low cost FPGA/ASIC)")
    print(f"  * Average Active Power   : {st['power']['average_power_uw']:.2f} μW")
    print(f"  * Standby Duty Cycle     : {st['power']['sleep_pct']:.1f} %")
    print(f"  * Projected Battery Life : {st['power']['battery_life_days']:.1f} {days_unit} on 200 mAh Wearable Battery")
    print("=" * 75)
    
    if all_pass:
        print(f"{tr('reg_all_pass', lang)}\n")
    else:
        print("  >>> REGRESSION TEST FAILURES DETECTED <<<\n")
        
    return all_pass

def run_scenario_sim(vcd_path: str = "sim/waves_soc.vcd", dashboard_path: str = "sim/simulator_dashboard.html", lang: str = "zh-TW"):
    set_language(lang)
    print("\n" + "=" * 75)
    print(f"  [End-to-End Voice Wakeup Scenario Simulation] (Lang: {lang})")
    print("=" * 75)
    print(f"  Waveform Output : {vcd_path}")
    print(f"  Dashboard Output: {dashboard_path}")
    
    soc = SmartwatchSoC(firmware_hex="sw/firmware.hex", vcd_output=vcd_path)
    
    print("\n[Phase 1] SoC Power-On Reset & Firmware Bootloader...")
    while not soc.cpu.is_sleeping and soc.total_cycles < 1000:
        soc.step_single_cycle()
        
    print(f"  -> System Boot Finished @ Cycle {soc.total_cycles}")
    print(f"  -> Debug LED: 0x{soc.bus.debug_leds:02x} ({soc.get_system_status()['leds']['desc']})")
    print(f"  -> System enters ultra-low power standby sleep (< 20 uW).")

    print("\n[Phase 2] Simulating Microphone Stream (Silence followed by Wakeup Voice)...")
    pcm = generate_pcm_scenario()
    soc.feed_pcm_samples(pcm)

    print("  -> Streaming audio samples through CIC decimator & Hardware VAD...")
    soc.run_until(lambda s: s.bus.debug_leds in (0xAA, 0x55), max_cycles=100_000)

    st = soc.get_system_status()
    days_unit = "天" if lang.startswith("zh") else ("日" if lang == "ja" else "Days")
    months_unit = "個月" if lang.startswith("zh") else ("ヶ月" if lang == "ja" else "Months")
    print("\n[Phase 3] Wake-up & Classification Complete:")
    print(f"  -> Final Status LED       : {st['leds']['val']} ({st['leds']['desc']})")
    print(f"  -> Total Simulated Time   : {st['sim_time_ms']:.2f} ms ({st['total_cycles']} Cycles)")
    print(f"  -> Level-1 VAD Decision   : Speech Active = {st['vad']['speech_active']}, Energy = {st['vad']['current_energy']}")
    print(f"  -> Level-2 NPU Results    : State = {st['npu']['state']}, Keyword Detected = {st['npu']['keyword_detected']}")
    print(f"  -> Classification Scores  : Class 0 = {st['npu']['score_0']}, Class 1 = {st['npu']['score_1']}")
    print(f"  -> Standby Sleep Duty     : {st['power']['sleep_pct']:.1f} %")
    print(f"  -> Average System Power   : {st['power']['average_power_uw']:.2f} μW")
    print(f"  -> Projected Battery Life : {st['power']['battery_life_days']:.1f} {days_unit} ({st['power']['battery_life_days']/30.4:.1f} {months_unit})")

    soc.close()
    print(f"\n[Phase 4] Exporting Digital Waveforms & Dashboard:")
    print(f"  -> Digital Waveform saved: {vcd_path} (Ready for GTKWave / PulseView)")
    
    generate_dashboard_html(st, soc.instruction_trace, dashboard_path, default_lang=lang)
    print("=" * 75 + "\n")
    return True

def main():
    parser = argparse.ArgumentParser(description="Smartwatch SoC Multi-Mode Simulator with i18n Multi-Language Support")
    parser.add_argument("--mode", choices=["regression", "scenario", "interactive", "dashboard"], default="scenario",
                        help="Simulation execution mode (default: scenario)")
    parser.add_argument("--firmware", default="sw/firmware.hex", help="Firmware 32-bit hex file path")
    parser.add_argument("--vcd", default="sim/waves_soc.vcd", help="Output VCD waveform file")
    parser.add_argument("--dashboard", default="sim/simulator_dashboard.html", help="Output HTML5 dashboard file")
    parser.add_argument("--lang", default="zh-TW", choices=["zh-TW", "en", "zh-CN", "ja"],
                        help="UI and reporting language (zh-TW, en, zh-CN, ja; default: zh-TW)")
    
    args = parser.parse_args()

    if args.mode == "regression":
        ok = run_regression_tests(lang=args.lang)
        sys.exit(0 if ok else 1)
    elif args.mode == "scenario":
        run_scenario_sim(vcd_path=args.vcd, dashboard_path=args.dashboard, lang=args.lang)
    elif args.mode == "interactive":
        cli = InteractiveSimulatorCLI(firmware_hex=args.firmware, vcd_output=args.vcd, lang=args.lang)
        cli.run_cli()
    elif args.mode == "dashboard":
        run_scenario_sim(vcd_path=args.vcd, dashboard_path=args.dashboard, lang=args.lang)

if __name__ == "__main__":
    main()
